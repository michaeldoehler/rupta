import { expect, test, type Page } from '@playwright/test'

async function start(page: Page, path: string) {
  await page.goto('/acme/issues?mock=demo&mock_latency=0')
  await expect(page.getByRole('grid', { name: 'Issues' }).getByRole('row').first()).toBeVisible()
  await page.goto(path)
}

test('integrations: connect a tracker, see the webhook secret once, rotate it and test', async ({ page }) => {
  await start(page, '/acme/settings/integrations')
  const list = page.getByRole('list', { name: 'Integrations' })
  await expect(list.getByRole('listitem', { name: 'GitHub' }).getByText('error')).toBeVisible()
  await page.getByRole('button', { name: 'Connect tracker' }).click()
  const dialog = page.getByRole('dialog', { name: 'Connect an issue tracker' })
  // The tracker picker is a radio group of logo tiles, moved with the arrow keys.
  const picker = dialog.getByRole('radiogroup', { name: 'Tracker' })
  await picker.getByRole('radio', { name: 'Jira Cloud' }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(picker.getByRole('radio', { name: 'Jira Data Center' })).toBeChecked()
  await expect(dialog.getByRole('img', { name: 'Jira Data Center' })).toBeVisible()
  await page.keyboard.press('ArrowLeft')
  await expect(picker.getByRole('radio', { name: 'Jira Cloud' })).toBeChecked()
  await dialog.getByRole('button', { name: 'Connect' }).click()
  await expect(dialog.getByText('Enter the site url.')).toBeVisible()
  await expect(dialog.getByLabel('Name')).toHaveValue('Jira Cloud')
  await dialog.getByLabel('Site URL').fill('https://ops.atlassian.net')
  await dialog.getByLabel('Account email').fill('bot@acme.dev')
  await dialog.getByLabel('API token').fill('ATATT-good')
  await dialog.getByRole('button', { name: 'Connect' }).click()
  const webhook = page.getByRole('dialog', { name: 'Set up the webhook in Jira Cloud' })
  await expect(webhook.getByText(/^whsec_/)).toBeVisible()
  await webhook.getByRole('button', { name: 'Done' }).click()
  const added = list.getByRole('listitem', { name: 'Jira Cloud' })
  await expect(added.getByText('Webhook secret stored')).toBeVisible()
  await added.getByRole('button', { name: 'New secret' }).click()
  const rotated = page.getByRole('dialog', { name: 'Set up the webhook in Jira Cloud' })
  await expect(rotated.getByText(/^whsec_/)).toBeVisible()
  await rotated.getByRole('button', { name: 'Done' }).click()
  await added.getByRole('button', { name: 'Test' }).click()
  await expect(added.getByRole('status')).toHaveText(/Connection works/)
  await added.getByRole('switch', { name: 'Disable Jira Cloud' }).click()
  await expect(added.getByText('disabled')).toBeVisible()
})

