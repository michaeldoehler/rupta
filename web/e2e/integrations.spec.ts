test('integrations: create, link and unlink tickets from an issue', async ({ page }) => {
  await start(page, '/acme/issues')
  await page.getByRole('grid', { name: 'Issues' }).getByRole('row').first().getByRole('link').first().click()
  const section = page.getByTestId('linked-tickets')
  await expect(section).toBeVisible()
  await page.getByRole('button', { name: 'More issue actions' }).click()
  await page.getByRole('menuitem', { name: /Create ticket/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Create a ticket' })
  await expect(dialog.getByLabel('Title')).not.toHaveValue('')
  await dialog.getByRole('button', { name: 'Preview' }).click()
  await expect(dialog.getByText('Top tags')).toBeVisible()
  const before = await section.getByRole('listitem').count()
  // Projects without defaults ask where the ticket goes.
  const target = dialog.getByLabel('Jira project')
  if (await target.isVisible()) await target.fill('OPS')
  await dialog.getByRole('button', { name: 'Create ticket' }).click()
  await expect(section.getByRole('listitem')).toHaveCount(before + 1)

  await section.getByRole('button', { name: 'Link existing' }).click()
  const link = page.getByRole('dialog', { name: 'Link an existing ticket' })
  await link.getByRole('textbox', { name: 'Ticket' }).fill('OPS-404')
  await link.getByRole('button', { name: 'Link ticket' }).click()
  await expect(link.getByText(/refused the request/)).toBeVisible()
  await link.getByRole('textbox', { name: 'Ticket' }).fill('https://acme.atlassian.net/browse/OPS-77')
  await link.getByRole('button', { name: 'Link ticket' }).click()
  await expect(section.getByRole('link', { name: 'Open OPS-77 in Jira' })).toBeVisible()
  await section.getByRole('button', { name: 'Unlink OPS-77' }).click()
  await expect(section.getByRole('link', { name: 'Open OPS-77 in Jira' })).toBeHidden()

  await page.getByRole('link', { name: /^Activity/ }).click()
  await expect(page.getByText(/unlinked .*OPS-77/).first()).toBeVisible()
})

