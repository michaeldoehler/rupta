test('replays: list, player with markers and panels', async ({ page }) => {
  await start(page, '/acme/replays')
  await page.getByRole('grid', { name: 'Replays' }).getByRole('link').first().click()
  const player = page.getByTestId('replay-player')
  await expect(player).toBeVisible()
  await expect(player.locator('iframe')).toBeAttached()
  await expect(player.locator('[data-marker="click"]').first()).toBeAttached()
  await expect(player.locator('[data-marker="error"]').first()).toBeAttached()
  await player.getByRole('button', { name: 'Play' }).first().click()
  await page.waitForTimeout(1500)
  await expect(player.getByRole('slider', { name: 'Playback position' })).not.toHaveAttribute('aria-valuenow', '0')
  await page.getByRole('tab', { name: /Network/ }).click()
  await page.getByRole('tabpanel').getByRole('button').filter({ hasText: '502' }).click()
  await expect(player.getByRole('slider', { name: 'Playback position' })).toHaveAttribute('aria-valuenow', '15')
  await page.getByRole('tab', { name: /Console/ }).click()
  await expect(page.getByRole('tabpanel')).toContainText('Checkout failed')
})

