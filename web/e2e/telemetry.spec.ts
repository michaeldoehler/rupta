test('logs: query with autocomplete, facets, expand a row and live tail', async ({ page }) => {
  await start(page, '/acme/logs')
  const grid = page.getByRole('grid', { name: 'Log lines' })
  await expect(grid.getByRole('row').first()).toBeVisible()
  const search = page.getByRole('combobox', { name: 'Search logs' })
  await search.click()
  await search.pressSequentially('lev')
  await expect(page.getByRole('option', { name: /^level:/ })).toBeVisible()
  await page.keyboard.press('Tab')
  await search.pressSequentially('err')
  await page.keyboard.press('Enter')
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL(/query=level%3Aerror/)
  await expect(grid.getByRole('row').first()).toContainText('error')
  await grid.getByRole('row').first().click()
  await expect(page.getByRole('table').getByText('service.name')).toBeVisible()
  await page.getByRole('region', { name: 'Facet service.name' }).getByRole('button').first().click()
  await expect(page).toHaveURL(/service.name/)
  await page.getByRole('button', { name: 'Live tail' }).click()
  await expect(page.getByRole('status').getByText('Live', { exact: true })).toBeVisible({ timeout: 10_000 })
  await page.getByRole('button', { name: 'Pause' }).click()
  await expect(page.getByRole('status').getByText('Paused while you scroll')).toBeVisible()
})

