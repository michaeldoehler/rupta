import { expect, test, type Page } from '@playwright/test'

async function start(page: Page, path: string) {
  await page.goto('/acme/issues?mock=demo&mock_latency=0')
  await expect(page.getByRole('grid', { name: 'Issues' }).getByRole('row').first()).toBeVisible()
  await page.goto(path)
}

test('performance: transactions, summary with web vitals, trace waterfall and span details', async ({ page }) => {
  await start(page, '/acme/performance')
  const table = page.getByRole('table', { name: 'Transactions' })
  await expect(table.getByRole('row').nth(1)).toBeVisible()
  await page.getByRole('button', { name: 'Sort by p95' }).click()
  await expect(page).toHaveURL(/sort=p95/)
  await page.getByLabel('Search transactions').fill('checkout')
  await table
    .getByRole('link', { name: /\/checkout/ })
    .first()
    .click()
  await expect(page).toHaveURL(/performance\/summary/)
  await expect(page.getByTestId('vital-lcp')).toBeVisible()
  await expect(page.getByRole('img', { name: 'Duration histogram' })).toBeVisible()
  await page.getByRole('table', { name: 'Slowest samples' }).getByRole('link').first().click()
  await expect(page).toHaveURL(/\/acme\/traces\/[0-9a-f]{32}/)
  const tree = page.getByRole('treegrid', { name: 'Spans' })
  await expect(tree.getByRole('row').first()).toBeVisible()
  const before = await tree.getByRole('row').count()
  await tree.getByRole('row').first().getByRole('button', { name: 'Collapse' }).click()
  await expect(tree.getByRole('row')).toHaveCount(1)
  await page.getByRole('button', { name: 'Expand all' }).click()
  await expect(tree.getByRole('row')).toHaveCount(before)
  await tree.getByRole('row').nth(2).click()
  await expect(page.getByTestId('span-drawer')).toBeVisible()
  await page.keyboard.press('j')
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('span-drawer')).toBeHidden()
  await page.getByRole('button', { name: 'Critical path' }).click()
  await expect(page.getByRole('button', { name: 'Critical path' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Zoom in' }).click()
  await expect(page.getByRole('button', { name: /Reset/ })).toBeEnabled()
})

test('issue event links to its trace; issues have a replays tab', async ({ page }) => {
  await start(page, '/acme/issues?sort=freq')
  await page.getByRole('grid', { name: 'Issues' }).getByRole('row').first().locator('[data-issue-link]').click()
  await expect(page.locator('#exception, #message').first()).toBeVisible()
  const issueUrl = page.url()
  await page.getByRole('navigation', { name: 'Issue sections' }).getByRole('link', { name: 'Replays' }).click()
  await expect(page.getByText(/sessions? with this error|No replays for this issue/)).toBeVisible()
  await page.goto(issueUrl)
  await page.getByRole('link', { name: /^Trace [0-9a-f]{8}/ }).click()
  await expect(page).toHaveURL(/\/acme\/traces\/[0-9a-f]{32}\?span=/)
  await expect(page.getByTestId('span-drawer')).toBeVisible()
  await expect(page.getByTestId('span-drawer').getByText('Errors (1)')).toBeVisible()
})

